/**
 * 특정 포켓몬이 배울 수 있는 모든 기술 리스트를 객체 배열로 반환합니다.
 * @param {object|string} pokemon - 포켓몬 객체 또는 ID/이름
 * @returns {Array<object>} [{ name, type, category: "물리"|"특수"|"변화", power, accur, pp, text, isImplemented }]
 */
export const getSkillListForPokemon = (pokemon) => {
  if (!pokemon) return [];

  const rawKey = typeof pokemon === "string" ? pokemon : pokemon.pokemon_id || pokemon.id || pokemon.origin?.pokemon_id || pokemon.origin?.id || pokemon.name;

  const key = POKEMON_SKILL_ALIASES[rawKey] || rawKey;

  // 도감번호 기본형 (예: "0006-x" -> "0006")
  const baseKey = key.includes("-") ? key.split("-")[0] : key;

  const rawEntry = POKEMON_SKILLS[key] || POKEMON_SKILLS[baseKey] || [];
  const isStructured = !Array.isArray(rawEntry) && typeof rawEntry === "object";
  const coreList = isStructured ? rawEntry.core || [] : [];
  const coreSet = new Set(coreList);
  let skillNames = isStructured ? [...(rawEntry.core || []), ...(rawEntry.others || [])] : rawEntry;

  // 포켓몬이 현재 가지고 있는 기술이 있다면(커스텀 등) 무조건 리스트에 포함
  const currentSkills = [];
  if (typeof pokemon === "object") {
    if (pokemon.skill) {
      [1, 2, 3, 4].forEach((num) => {
        const s = pokemon.skill[num];
        if (s?.name && s.name !== "임시스킬") currentSkills.push(s.name);
      });
    }
    if (pokemon.skills) {
      const skArray = Array.isArray(pokemon.skills) ? pokemon.skills : Object.values(pokemon.skills);
      skArray.forEach((s) => {
        const sName = typeof s === "string" ? s : s?.name;
        if (sName && sName !== "임시스킬") currentSkills.push(sName);
      });
    }
  }

  // 장착 기술 상관없이: 주력기술(배열 순) + 그 외 공식 기술 + (공식 외 장착 기술)
  const allNames = Array.from(new Set([...skillNames, ...currentSkills]));

  const mappedList = allNames.map((name) => {
    // 1. 구현된 기술인지 확인 (allSkills / skillList)
    const implementedObj = allSkills.find((item) => item.name === name);
    if (implementedObj) {
      let category = "변화";
      if (implementedObj.stype === "atk") category = "물리";
      else if (implementedObj.stype === "catk") category = "특수";

      return {
        name: implementedObj.name,
        type: implementedObj.type,
        category,
        stype: implementedObj.stype,
        power: implementedObj.power || "-",
        accur: implementedObj.accur || "-",
        pp: implementedObj.pp,
        prior: implementedObj.prior !== undefined ? implementedObj.prior : 0,
        text: implementedObj.text || "효과 설명이 없습니다.",
        originText: implementedObj.originText !== undefined ? implementedObj.originText : implementedObj.text || "효과 설명이 없습니다.",
        isImplemented: true,
        isCore: coreSet.has(name),
      };
    }

    // 2. 미구현 기술 목록에서 확인
    const unimp = UNIMPLEMENTED_SKILL_MAP[name];
    if (unimp) {
      return {
        ...unimp,
        prior: unimp.prior !== undefined ? unimp.prior : name === "눈사태" ? -4 : 0,
        originText: unimp.text,
        isImplemented: false,
        isCore: coreSet.has(name),
      };
    }

    // 3. 미정의 기술 폴백
    return {
      name,
      type: "노말",
      category: "변화",
      power: "-",
      accur: "-",
      pp: 10,
      prior: 0,
      text: "미구현된 기술입니다.",
      originText: "미구현된 기술입니다.",
      isImplemented: false,
      isCore: coreSet.has(name),
    };
  });

  // 정렬 기준:
  // 1. 주력 기술 (core 배열 채용률 순서대로)
  // 2. 구현 기술 (가나다 순)
  // 3. 미구현 기술 (가나다 순)
  return mappedList.sort((a, b) => {
    if (a.isCore && b.isCore) {
      const idxA = coreList.indexOf(a.name);
      const idxB = coreList.indexOf(b.name);
      if (idxA !== -1 && idxB !== -1) return idxA - idxB;
      if (idxA !== -1) return -1;
      if (idxB !== -1) return 1;
      return a.name.localeCompare(b.name, "ko");
    }
    if (a.isCore) return -1;
    if (b.isCore) return 1;

    if (a.isImplemented && !b.isImplemented) return -1;
    if (!a.isImplemented && b.isImplemented) return 1;

    return a.name.localeCompare(b.name, "ko");
  });
};

